import json
import logging
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from urllib import error as urllib_error
from urllib import request as urllib_request

from app.config import _has_real_value, settings

logger = logging.getLogger("sahvion.email")


def _send_via_resend(recipient_email: str, subject: str, body: str) -> bool:
    api_key = settings.RESEND_API_KEY.strip()
    from_email = settings.RESEND_FROM_EMAIL.strip()

    if not _has_real_value(api_key) or not _has_real_value(from_email):
        logger.warning("Resend email provider is not configured. Set real RESEND_API_KEY and RESEND_FROM_EMAIL values in backend/.env.")
        return False

    payload = {
        "from": from_email,
        "to": [recipient_email],
        "subject": subject,
        "html": f"<pre>{body}</pre>",
        "text": body,
    }

    req = urllib_request.Request(
        "https://api.resend.com/emails",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "Accept": "application/json",
        },
        method="POST",
    )

    try:
        logger.info("Email sending started via Resend for %s", recipient_email)
        with urllib_request.urlopen(req, timeout=30) as response:
            status = getattr(response, "status", response.getcode())
            logger.info("Resend email response status=%s for %s", status, recipient_email)
            return status in {200, 201, 202}
    except urllib_error.HTTPError as exc:
        body_text = exc.read().decode("utf-8", errors="ignore")
        logger.error("Resend email send failed for %s: %s %s", recipient_email, exc.code, body_text)
        return False
    except Exception as exc:  # pragma: no cover - defensive network branch
        logger.exception("Resend email send raised an unexpected exception for %s", recipient_email)
        return False


def _send_via_smtp(recipient_email: str, subject: str, body: str) -> bool:
    if not settings.SMTP_HOST or not settings.SMTP_USERNAME or not settings.SMTP_PASSWORD:
        logger.warning(
            "SMTP provider is not configured. Set SMTP_HOST, SMTP_USERNAME, and SMTP_PASSWORD in backend/.env "
            "to send contact emails. Inquiry was not mailed."
        )
        return False

    try:
        logger.info("Email sending started via SMTP for %s", recipient_email)
        msg = MIMEMultipart()
        msg["From"] = settings.SMTP_USERNAME
        msg["To"] = recipient_email
        msg["Subject"] = subject
        msg.attach(MIMEText(body, "plain"))

        if settings.SMTP_USE_SSL:
            with smtplib.SMTP_SSL(settings.SMTP_HOST, settings.SMTP_PORT, timeout=15) as server:
                server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
                server.send_message(msg)
        else:
            with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT, timeout=15) as server:
                if settings.SMTP_USE_TLS:
                    server.starttls()
                server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
                server.send_message(msg)

        logger.info("Email sending successful via SMTP for %s", recipient_email)
        return True
    except Exception as exc:
        logger.exception("Email sending failed via SMTP for %s: %s", recipient_email, exc)
        return False


def send_contact_notification(
    name: str,
    email: str,
    phone: str | None,
    company: str | None,
    service: str,
    message: str,
) -> bool:
    """Dispatch contact enquiry email to the configured inbox using a tracked transactional provider."""
    recipient_email = settings.CONTACT_EMAIL or "sahvion26@gmail.com"
    subject = f"[SAHVION INQUIRY] New Project Lead: {name} ({service})"

    body = f"""
==================================================
SAHVION — NEW INCOMING PROJECT INQUIRY
==================================================

Client Name:    {name}
Client Email:   {email}
Contact Phone:  {phone or 'Not provided'}
Company:        {company or 'Not provided'}
Service Track:  {service}

Project Vision / Message:
--------------------------------------------------
{message}
--------------------------------------------------

Timestamp: Generated by SAHVION FastAPI Engine
Destination: {recipient_email}
==================================================
"""

    provider = settings.EMAIL_PROVIDER.lower()
    logger.info("Email sending requested for %s using provider=%s", recipient_email, provider)

    if provider == "resend":
        successful = _send_via_resend(recipient_email, subject, body)
    elif provider == "smtp":
        successful = _send_via_smtp(recipient_email, subject, body)
    elif provider == "disabled":
        logger.warning("Email provider is disabled by configuration; no delivery attempts were made.")
        successful = False
    else:
        logger.warning("Unsupported EMAIL_PROVIDER '%s'. Expected 'resend', 'smtp', or 'disabled'.", provider)
        successful = False

    if successful:
        logger.info("Email sending successful for %s to %s", name, recipient_email)
        return True

    logger.error("Email sending failed for %s to %s", name, recipient_email)
    return False
